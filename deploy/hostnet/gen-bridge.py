# prds#166: generates openpak-hostnet-bridge (traefik.yml, dynamic.yml, quadlet) into argv[1].
import sys
out = sys.argv[1]
# host-network services reach these on 127.0.0.1 at the same port (published on loopback)
loop = [(5432,"openpak-postgres:5432"),(9000,"openpak-minio:9000"),(20050,"openpak-nn-account:20050"),
        (20051,"openpak-nn-account:20051"),(20061,"openpak-nn-friends:20061"),(20131,"openpak-chat:20131"),
        (20221,"openpak-achievements:20221"),(20231,"openpak-title-storage:20231"),(20251,"openpak-matchmaking:20251")]
# bridge callers of a host-network service by name: alias, port on the bridge -> port on the host
alias_tcp = [("openpak-mario-kart-7",22855,22738),("openpak-mario-kart-8",22853,22853),("openpak-super-mario-maker",22584,22584),
             ("openpak-monster-hunter-generations-ultimate",22120,22120),("openpak-monster-hunter-generations-ultimate",22122,22122),
             ("openpak-among-us",22600,22600),("openpak-playfab",22650,22650),("openpak-spelunky2",22660,22660)]
# website rankings reader: http://<alias>:9090 -> the service's own RANKINGS_ADDR port on the host
rank = [l.split() for l in open(__file__.rsplit("/", 1)[0] + "/rankings-ports.txt") if l.strip() and "BUSY" not in l]
rank += [["openpak-mario-kart-7","22737"],["openpak-mario-kart-8","22857"],["openpak-super-mario-maker","22587"],["openpak-spelunky2","22667"]]
eps = [(f"p{p}", p) for p,_ in loop] + [(f"a{p}", p) for _,p,_ in alias_tcp] + [("rankings", 9090)]
t = ["entryPoints:"] + [f'  {n}:\n    address: ":{p}"' for n,p in eps]
t += ["providers:\n  file:\n    filename: /etc/traefik/dynamic.yml", "log:\n  level: WARN"]
open(f"{out}/traefik.yml","w").write("\n".join(t)+"\n")
tcp = [(f"p{p}", a) for p,a in loop] + [(f"a{p}", f"host.containers.internal:{h}") for _,p,h in alias_tcp]
d = ["# prds#166, generated by gen-bridge.py. tcp p*: host-network services reach these openpak.network services on",
     "# 127.0.0.1 at the same port. tcp a* and http: bridge containers still call host-network services by name",
     "# (NetworkAlias on this container); this sends them to the service's port on the host.",
     "tcp:","  routers:"]
d += [f"    {n}:\n      entryPoints: [{n}]\n      rule: HostSNI(`*`)\n      service: {n}" for n,_ in tcp]
d += ["  services:"] + [f"    {n}:\n      loadBalancer:\n        servers:\n        - address: {a}" for n,a in tcp]
d += ["http:","  routers:"]
d += [f"    rk-{c[8:]}:\n      entryPoints: [rankings]\n      rule: Host(`{c}`)\n      service: rk-{c[8:]}" for c,_ in rank]
d += ["  services:"] + [f"    rk-{c[8:]}:\n      loadBalancer:\n        servers:\n        - url: http://host.containers.internal:{p}" for c,p in rank]
open(f"{out}/dynamic.yml","w").write("\n".join(d)+"\n")
aliases = sorted({c for c,_ in rank} | {a for a,_,_ in alias_tcp})
q = ["[Unit]","Description=Loopback bridge for host-network console UDP services (prds#166): openpak.network TCP services on 127.0.0.1 at the same port, and the moved services' names back on openpak.network",
     "Wants=openpak-postgres.service openpak-minio.service openpak-nn-account.service openpak-nn-friends.service","After=openpak-postgres.service openpak-minio.service","",
     "[Container]","ContainerName=openpak-hostnet-bridge","Image=docker.io/library/traefik:v3.3","Annotation=run.oci.keyring=false","Network=openpak.network"]
q += [f"NetworkAlias={a}" for a in aliases]
q += [f"PublishPort=127.0.0.1:{p}:{p}" for p,_ in loop]
q += ["Volume=%h/openpak/deploy/hostnet/bridge:/etc/traefik:ro,Z","Exec=--configFile=/etc/traefik/traefik.yml","","[Service]","Restart=always","","[Install]","WantedBy=default.target"]
open(f"{out}/openpak-hostnet-bridge.container","w").write("\n".join(q)+"\n")
print(len(aliases),"aliases", len(eps),"entrypoints", len(rank),"rankings")
